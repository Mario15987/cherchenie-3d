def make_project(kind: str) -> tuple[Project, dict]:
    """Новый документ вида kind и то, что окну сделать после создания: вкладка, раздел каталога, сетка, редактор."""
    if kind not in SETUP:
        raise ValueError(f"вид документа: {', '.join(SETUP)}")
    cfg = SETUP[kind]
    p = Project(name=cfg["name"])
    ops.set_canvas(p, cfg["canvas"])
    p.eskd["doc"] = kind
    if p.frame:
        p.frame["form"] = cfg.get("form", "1")
        if cfg.get("scale"):
            p.frame["scale"] = cfg["scale"]
    if cfg.get("suffix"):
        p.designation = f"АБВГ.000000.001 {cfg['suffix']}"
    if cfg.get("scheme"):
        from . import eskd

        p.designation = "АБВГ.000000.001"
        eskd.set_scheme(p, *cfg["scheme"])
    return p, {k: cfg.get(k) for k in ("tab", "library", "iso", "style", "after")}
